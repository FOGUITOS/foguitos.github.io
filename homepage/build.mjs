function renderFeature(feature) {
  const caption = feature.caption ? `\n            <figcaption>${escape(feature.caption)}</figcaption>` : "";
  const description = feature.description ? `\n            <p>${escape(feature.description)}</p>` : "";
  const link = feature.documentationHref
    ? `\n            <a class="button button-secondary" href="${escape(feature.documentationHref)}">Read the documentation</a>`
    : "";
  return `        <article class="home-feature">
          <div>
            <h3>${escape(feature.title)}</h3>${description}${link}
          </div>
          <figure>
            ${renderMedia(feature)}${caption}
          </figure>
        </article>`;
}

function renderShowcase() {
  const features = showcase.features.filter((feature) => feature.visible);
  if (!features.length) return "";

  return `    <section class="template-section home-section" id="features" aria-labelledby="features-title" tabindex="-1">
      <div class="wrap">
        <h2 id="features-title">${escape(showcase.heading)}</h2>
        <div class="home-features">
${features.map(renderFeature).join("\n")}
        </div>
      </div>
    </section>`;
}

const page = readFileSync(pageFile, "utf8");
const first = page.indexOf(start);
const last = page.indexOf(end);
if (first < 0 || last <= first || page.lastIndexOf(start) !== first || page.lastIndexOf(end) !== last) {
  throw new Error("Expected exactly one homepage region in dist/index.html.");
}

const newline = page.includes("\r\n") ? "\r\n" : "\n";
const sections = [renderHero(), renderWorkflow(), renderMultiphysics(), renderNumericalFramework(), renderShowcase()].filter(Boolean);
const block = [start, ...sections, end].join("\n\n").replaceAll("\n", newline);
const output = page.slice(0, first) + block + page.slice(last + end.length);

if (process.argv.includes("--check")) {
  if (output !== page) {
    throw new Error("Homepage HTML is out of date. Run node homepage/build.mjs.");
  }
  console.log("Homepage HTML is up to date.");
} else {
  if (output !== page) writeFileSync(pageFile, output, "utf8");
  console.log("Built the homepage in dist/index.html.");
}
