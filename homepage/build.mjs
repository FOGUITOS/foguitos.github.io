import { readFileSync, statSync, writeFileSync } from "node:fs";
import { isAbsolute, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { hero, workflow, multiphysics, numerical, showcase } from "./content.mjs";

const pageFile = new URL("../dist/index.html", import.meta.url);
const mediaRoot = fileURLToPath(new URL("../dist/homepage-media/", import.meta.url));
const start = "    <!-- Homepage start. Generated by node homepage/build.mjs. -->";
const end = "    <!-- Homepage end. -->";

const entities = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" };
const escape = (value) => String(value).replace(/[&<>"]/g, (character) => entities[character]);

function mediaUrl(file) {
  const asset = resolve(mediaRoot, file);
  const local = relative(mediaRoot, asset);
  if (!local || local === ".." || local.startsWith(`..${sep}`) || isAbsolute(local)) {
    throw new Error("Homepage media must be inside dist/homepage-media.");
  }
  if (!statSync(asset, { throwIfNoEntry: false })?.isFile()) {
    throw new Error(`Homepage media file is missing: ${file}`);
  }
  return `homepage-media/${local.split(sep).map(encodeURIComponent).join("/")}`;
}

function renderMedia(entry, eager = false) {
  const { media } = entry;
  const label = escape(media?.label ?? entry.mediaLabel ?? entry.title);
  if (!media) {
    return `<div class="home-media home-media--reserved"><span>${label}</span></div>`;
  }

  const src = mediaUrl(media.file);
  const loading = eager ? "eager" : "lazy";
  let element;
  switch (media.type) {
    case "image":
      element = `<img src="${src}" alt="${label}" loading="${loading}" decoding="async">`;
      break;
    case "video":
      element = `<video src="${src}" aria-label="${label}" controls playsinline preload="none"></video>`;
      break;
    case "embed":
      element = `<iframe src="${src}" title="${label}" loading="${loading}" allowfullscreen></iframe>`;
      break;
    default:
      throw new Error(`Unknown homepage media type: ${media.type}`);
  }
  return `<div class="home-media">${element}</div>`;
}

function renderList(items, className) {
  return `<ul class="${className}" role="list">${items.map((item) => `<li>${escape(item)}</li>`).join("")}</ul>`;
}

function renderHeading(section, id) {
  const description = section.description
    ? `\n          <p class="home-summary">${escape(section.description)}</p>`
    : "";
  return `<p class="home-eyebrow">${escape(section.eyebrow)}</p>
          <h2 id="${id}">${escape(section.heading)}</h2>${description}`;
}

function renderHero() {
  return `    <section class="hero home-hero" id="home" aria-labelledby="hero-title" tabindex="-1" data-enter>
      <div class="wrap home-hero-grid">
        <div class="home-hero-copy">
          <p class="home-eyebrow">${escape(hero.eyebrow)}</p>
          <h1 id="hero-title">${hero.heading.map((line) => `<span>${escape(line)}</span>`).join(" ")}</h1>
          <div class="home-hero-description">
            ${hero.paragraphs.map((paragraph) => `<p>${escape(paragraph)}</p>`).join("\n            ")}
          </div>
          <div class="home-actions">
            <a class="button button-primary" href="#workflow">Explore the workflow</a>
            <a class="button button-secondary" href="#demo">View demo gallery</a>
          </div>
        </div>
        ${renderMedia(hero, true)}
      </div>
    </section>`;
}

function renderWorkflow() {
  const cards = workflow.modules.map((module, index) => `          <li class="home-module">
            <span class="home-step" aria-hidden="true">${String(index + 1).padStart(2, "0")}</span>
            <h3>${escape(module.title)}</h3>
            ${renderMedia(module)}
            <p>${escape(module.description)}</p>
            ${renderList(module.keywords, "home-keywords")}
          </li>`);
  return `    <section class="template-section tinted-section home-section" id="workflow" aria-labelledby="workflow-title" tabindex="-1">
      <div class="wrap">
        <div class="home-section-heading">
          ${renderHeading(workflow, "workflow-title")}
        </div>
        <ol class="home-modules" role="list">
${cards.join("\n")}
        </ol>
        <div class="home-dataflow" role="group" aria-label="Inputs to the thermal solver">
          <ul class="home-dataflow-inputs" role="list">
            <li><strong>Geometry and materials</strong><span>Voxel model</span></li>
            <li><strong>Power losses</strong><span>Direct input or electrical solver output</span></li>
            <li><strong>Thermal boundaries</strong><span>Convection and surface conditions</span></li>
          </ul>
          <span class="home-dataflow-arrow" aria-hidden="true"></span>
          <p class="home-dataflow-target">Thermal solver</p>
        </div>
        <p class="home-workflow-summary">${escape(workflow.summary)}</p>
      </div>
    </section>`;
}

function renderMultiphysics() {
  const cards = multiphysics.modules.map((module) => {
    const status = module.status ? `<span class="home-status">${escape(module.status)}</span>` : "";
    const capabilities = module.status ? "Research directions" : "Key capabilities";
    return `          <li class="home-solver">
            <div class="home-solver-heading"><h3>${escape(module.title)}</h3>${status}</div>
            <p>${escape(module.description)}</p>
            ${renderMedia(module)}
            <p class="home-capability-label">${capabilities}</p>
            ${renderList(module.capabilities, "home-keywords")}
          </li>`;
  });
  return `    <section class="template-section home-section" id="multiphysics" aria-labelledby="multiphysics-title" tabindex="-1">
      <div class="wrap">
        <div class="home-section-heading">
          ${renderHeading(multiphysics, "multiphysics-title")}
        </div>
        <ul class="home-solvers" role="list">
${cards.join("\n")}
        </ul>
      </div>
    </section>`;
}

